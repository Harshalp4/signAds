// Regenerates lib/image-dimensions.ts from the files in public/images.
// Run after adding or replacing an image: node scripts/image-dimensions.mjs
import { readdir, readFile, writeFile } from 'node:fs/promises';
import { join } from 'node:path';

const IMAGES = new URL('../public/images/', import.meta.url);
const OUT = new URL('../lib/image-dimensions.ts', import.meta.url);

// Minimal WebP header reader: VP8X, lossless (VP8L) and lossy (VP8 ) chunks.
function webpSize(buf) {
  if (buf.toString('ascii', 0, 4) !== 'RIFF' || buf.toString('ascii', 8, 12) !== 'WEBP') return null;
  const chunk = buf.toString('ascii', 12, 16);
  if (chunk === 'VP8X') return [(buf.readUIntLE(24, 3) & 0xffffff) + 1, (buf.readUIntLE(27, 3) & 0xffffff) + 1];
  if (chunk === 'VP8L') {
    const b = buf.readUInt32LE(21);
    return [(b & 0x3fff) + 1, ((b >> 14) & 0x3fff) + 1];
  }
  if (chunk === 'VP8 ') return [buf.readUInt16LE(26) & 0x3fff, buf.readUInt16LE(28) & 0x3fff];
  return null;
}

const files = (await readdir(IMAGES)).filter((f) => f.endsWith('.webp')).sort();
const rows = [];
for (const file of files) {
  const size = webpSize(await readFile(join(IMAGES.pathname, file)));
  if (!size) {
    console.warn(`skipped ${file}: unrecognised WebP header`);
    continue;
  }
  rows.push(`  ${JSON.stringify(file.replace(/\.webp$/, ''))}: [${size[0]}, ${size[1]}],`);
}

await writeFile(
  OUT,
  [
    '// Intrinsic pixel dimensions of every file in public/images.',
    '// Generated by scripts/image-dimensions.mjs — run it after adding or replacing an image.',
    'export const imageDimensions: Record<string, [number, number]> = {',
    ...rows,
    '};',
    'export const dimensionsFor = (image: string): [number, number] => imageDimensions[image.replace(/^\\/images\\//, "").replace(/\\.webp$/, "")] ?? [1200, 800];',
    '',
  ].join('\n'),
);
console.log(`wrote ${rows.length} entries`);
